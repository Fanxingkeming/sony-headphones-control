#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Build the one-file Windows exe.

    python build.py                 # full build (UPX if available)
    python build.py --no-upx        # skip UPX
    python build.py --console       # console build for debugging

Outputs dist/SonyHeadphonesControl.exe.
"""
import os
import shutil
import struct
import subprocess
import sys

import tray

HERE = os.path.dirname(os.path.abspath(__file__))
DIST = os.environ.get("SHC_OUT") or HERE   # land the deliverable in the app folder
ICON = os.path.join(HERE, "icon.ico")


def make_ico(path, sizes=(16, 32, 48)):
    """Prefer the real Sound Connect app logo generated by make_brand_assets.py.

    The old procedural DIB is kept as a fallback so a bare source checkout can
    still be built before the brand assets have been generated.
    """
    src = os.path.join(HERE, "assets", "app-icon.ico")
    if os.path.isfile(src) and os.environ.get("SHC_CLEAN") != "1":
        shutil.copyfile(src, path)
        print("icon: %s (%d bytes, Sound Connect app logo)" % (
            path, os.path.getsize(path)))
        return
    images = [(s, tray.icon_dib(s, ss=4)) for s in sizes]
    header = struct.pack("<HHH", 0, 1, len(images))
    offset = 6 + 16 * len(images)
    entries = b""
    for s, bits in images:
        w = 0 if s >= 256 else s
        entries += struct.pack("<BBBBHHII", w, w, 0, 0, 1, 32,
                               len(bits), offset)
        offset += len(bits)
    with open(path, "wb") as f:
        f.write(header + entries + b"".join(b for _, b in images))
    print("icon: %s (%d bytes, %s)" % (path, os.path.getsize(path), sizes))


def upx_dir():
    here = os.environ.get("TEMP", os.path.expanduser("~"))
    for root in (os.path.join(here, "upx", "upx-4.2.4-win64"),
                 os.path.join(here, "upx")):
        if os.path.isfile(os.path.join(root, "upx.exe")):
            return root
    return None


def main():
    argv = sys.argv[1:]
    make_ico(ICON)
    cmd = [sys.executable, "-m", "PyInstaller",
           "--noconfirm", "--clean", "--distpath", DIST,
           "--workpath", os.path.join(HERE, "build")]
    # `--windowed` / `--console` are makespec-only; the spec reads the env var.
    if "--console" in argv:
        os.environ["SHC_CONSOLE"] = "1"
    else:
        os.environ.pop("SHC_CONSOLE", None)
    if "--no-upx" in argv:
        cmd.append("--noupx")
    else:
        d = upx_dir()
        if d:
            print("UPX:", d)
            cmd += ["--upx-dir", d]
        else:
            print("UPX not found - building without it")
            cmd.append("--noupx")
    cmd.append(os.path.join(HERE, "build.spec"))
    print(" ".join(cmd))
    r = subprocess.run(cmd, cwd=HERE)
    if r.returncode:
        return r.returncode
    exe = os.path.join(DIST, "SonyHeadphonesControl.exe")
    if os.path.isfile(exe):
        size = os.path.getsize(exe)
        print("\nOK: %s  (%.2f MiB / %d bytes)" % (exe, size / 1048576, size))
    # PyInstaller's workpath is several times bigger than the exe; it is a
    # pure intermediate, so drop it to keep the project folder small.
    shutil.rmtree(os.path.join(HERE, "build"), ignore_errors=True)
    old_dist = os.path.join(HERE, "dist")
    if os.path.isdir(old_dist):
        shutil.rmtree(old_dist, ignore_errors=True)
    return 0


if __name__ == "__main__":
    sys.exit(main())
